import * as vscode from "vscode";
import assert from "node:assert/strict";
import { mkdirSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import type { PsdEditorProvider } from "../src/psd-editor-provider";
import { WorkbenchSettingsController } from "../src/workbench-settings-controller";
import { PsdExportController } from "../src/psd-export-controller";
import { EXPORT_SETTINGS_KEY, LEGACY_RESOURCE_DIRECTORY_KEY } from "../shared/workbench-settings";
import { RESOURCE_MANIFEST, makeSliceExportBatch, psdExportDirectory } from "../shared/psd-export";
import type { PsdAsset } from "../shared/psd-meta";
import { readWorkbenchSlices } from "../src/slice-resource-controller";
import { exportPrefab, inspectPrefabFile } from "../src/prefab-export-controller";
import { initialPrefabBase, inspectPrefab, mergePrefab } from "../shared/prefab-sync";
import { planPrefabExport } from "../shared/prefab-export";
import { makeNode } from "../shared/editor-ops";
import { createDefaultGameFlowDocument } from "../shared/model";

export async function settingsChecks(api: { psd: PsdEditorProvider }, root: string, directory: string): Promise<string[]> {
  const checks: string[] = [], settings = api.psd.settings;
  const resources = settings.directory("resources"), prefabs = settings.directory("prefabs");
  const first = vscode.Uri.file(join(directory, "resources-a")), second = vscode.Uri.file(join(directory, "resources-b")), prefab = vscode.Uri.file(join(directory, "prefabs"));
  for (const folder of [first, second, prefab]) mkdirSync(folder.fsPath);
  const source = vscode.Uri.file(join(directory, "settings-source.psd"));
  const exporter = new PsdExportController(settings, { uri: source });
  const asset: PsdAsset = { name: "设置验证.psd", sourceHash: "a".repeat(64), documentId: "settings-psd", hasEmbeddedIdentity: true, width: 10, height: 10, preview: "", layers: [{ key: 0, nativeId: 0, parentKey: null, name: "图标", group: false, left: 0, top: 0, width: 10, height: 10, hidden: false, identityOrigin: "embedded", metadata: { namespace: "com.codetypes.gameflow", version: 1, documentId: "settings-psd", layerId: "settings-layer" }, config: { enabled: true, name: "图标", nineGrid: null }, image: `data:image/png;base64,${readFileSync(join(root, "examples/star-sea-login/assets/status_dot.png")).toString("base64")}` }] };
  const batch = makeSliceExportBatch(asset), filename = "unclassified/" + batch.items[0].name + ".png";
  try {
    await settings.set("resources");
    assert.match((await readWorkbenchSlices(settings, [filename]))[0].error!, /根目录/);
    await assert.rejects(exporter.export(batch), /工作台设置/);
    await Promise.all([settings.set("resources", first), settings.set("prefabs", prefab)]);
    assert.equal(settings.directory("resources")?.toString(), first.toString());
    assert.equal(settings.directory("prefabs")?.toString(), prefab.toString());
    assert.equal(await exporter.export(batch), 1);
    assert.ok(existsSync(join(first.fsPath, filename))); assert.ok(existsSync(join(first.fsPath, RESOURCE_MANIFEST)));
    const sliceMeta=JSON.parse(readFileSync(join(first.fsPath,filename+".meta"),"utf8"));
    assert.match(sliceMeta.uuid,/^[a-f0-9-]{36}$/);
    assert.deepEqual(sliceMeta.importer.sizeGrid,[0,0,0,0,0]);
    await settings.set("resources", second);
    assert.equal(await exporter.export(batch), 1);
    assert.ok(existsSync(join(second.fsPath, filename))); assert.ok(existsSync(join(second.fsPath, RESOURCE_MANIFEST)));
    assert.equal(settings.directory("prefabs")?.toString(), prefab.toString());
    assert.equal(existsSync(source.fsPath), false); assert.equal(existsSync(source.fsPath.replace(/\.psd$/, ".meta.json")), false);
    checks.push("workspace settings keep resource and prefab directories independent", "existing exporter uses changed resource directory and writes PNG plus provenance", "missing directory rejects export without touching source documents");
    for (const folder of ["builtin", "shared", "unclassified"]) assert.ok(existsSync(join(second.fsPath, folder)));
    const loaded = (await readWorkbenchSlices(settings, [filename]))[0];
    assert.equal(loaded.error, undefined); assert.equal(loaded.description?.source.documentId, asset.documentId);
    assert.deepEqual(Buffer.from(loaded.base64!, "base64"), readFileSync(join(second.fsPath, filename)));
    const missing = (await readWorkbenchSlices(settings, ["unclassified/img_missing.png"]))[0];
    assert.equal(missing.exists, false); assert.match(missing.error!, /不存在/);
    const unsafe = (await readWorkbenchSlices(settings, ["../private.png"]))[0];
    assert.match(unsafe.error!, /相对 PNG/);
    checks.push("preview loads classified PNGs from the root ledger", "preview reports missing roots and files without fallback", "preview rejects traversal before resource filesystem access");
    const prototype = createDefaultGameFlowDocument("native-prefab");
    const button = makeNode("button", "button", 20, 20);
    const label = { ...makeNode("text", "caption", 0, 0), parentId: button.id, text: "登录" };
    prototype.pages = [{ id: "login", name: "原型导出", exportName: "原型导出", kind: "screen", frame: { x: 0, y: 0, width: 320, height: 240 }, nodes: [button, label] }];
    prototype.interactions = [];
    const plan = await planPrefabExport(prototype, prototype.pages[0], async () => ({ status: "error", error: "unexpected art binding" }));
    assert.deepEqual(plan.missing, []);
    assert.equal(await exportPrefab(settings, plan.batch), 1);
    const prefabFile = join(prefab.fsPath, plan.batch.name);
    const nativePrefab = JSON.parse(readFileSync(prefabFile, "utf8"));
    assert.match(JSON.parse(readFileSync(prefabFile+".meta","utf8")).uuid,/^[a-f0-9-]{36}$/);
    assert.equal(nativePrefab._$child[0]._$type, "UIButton");
    assert.ok(nativePrefab._$child[0].normalSkin.startsWith("res://"));
    assert.equal(nativePrefab._$child[0].text, undefined);
    assert.equal(nativePrefab._$child[0]._$child[0].text, "登录");
    assert.ok(existsSync(join(second.fsPath, "builtin/button/gray.png.meta")));
    const builtin = (await readWorkbenchSlices(settings, ["builtin/button/gray.png"]))[0];
    assert.equal(builtin.error, undefined);
    assert.equal(builtin.description?.source.documentId, "gameflow-builtin");
    const target = await vscode.workspace.openTextDocument(vscode.Uri.file(prefabFile));
    const savedPrefab = target.getText();
    const localEdit = new vscode.WorkspaceEdit();
    localEdit.insert(target.uri, new vscode.Position(0, 0), " ");
    assert.ok(await vscode.workspace.applyEdit(localEdit));
    assert.equal(target.isDirty, true);
    await assert.rejects(exportPrefab(settings, plan.batch), /未保存/);
    assert.equal(readFileSync(prefabFile, "utf8"), savedPrefab);
    const restore = new vscode.WorkspaceEdit();
    restore.replace(target.uri, new vscode.Range(target.positionAt(0), target.positionAt(target.getText().length)), savedPrefab);
    assert.ok(await vscode.workspace.applyEdit(restore));
    assert.ok(await target.save());
    checks.push("native Prefab export writes builtin PNG metadata ledger and independent labels", "native Prefab export protects dirty destination files");
    const edited=JSON.parse(savedPrefab);
    edited._$child[0]._$comp=[{_$type:"DebounceClick",interval:500}];
    edited._$child.push({_$type:"UILabel",_$id:"native-notice",name:"公告",text:"活动",width:80,height:24});
    await vscode.workspace.fs.writeFile(target.uri,Buffer.from(JSON.stringify(edited)));
    const snap=await inspectPrefabFile(settings,plan.batch);
    assert.equal(snap.skins?.[edited._$child[0].normalSkin],"builtin/button/gray.png");
    const updatedPage={...prototype.pages[0],prefabSync:initialPrefabBase(prototype,prototype.pages[0],plan.batch.name)};
    updatedPage.nodes=[...updatedPage.nodes,{...makeNode("text","newhelp1",0,0),name:"帮助"}];
    const {batch:nextBatch}=await planPrefabExport(prototype,updatedPage,async()=>({status:"error",error:"unexpected"}));
    const compare=inspectPrefab(prototype,updatedPage,nextBatch.name,snap.prefab!);
    const decisions=Object.fromEntries(compare.comparison.changes.map(c=>[c.key,c.suggested!]));
    const merged=mergePrefab(compare,decisions,nextBatch);
    let completed=false;
    await exportPrefab(settings,merged.batch,{hash:snap.hash,writePrefab:true,added:merged.added},snap.root,async()=>{completed=true;});
    const actual=JSON.parse(readFileSync(prefabFile,"utf8"));
    assert.ok(completed);
    assert.deepEqual(actual._$child[0]._$comp,edited._$child[0]._$comp);
    assert.ok(actual._$child.some((n:{name:string})=>n.name==="帮助"));
    assert.ok(merged.page.nodes.some(n=>n.name==="公告"));
    await assert.rejects(exportPrefab(settings,merged.batch,{hash:snap.hash,writePrefab:true,added:merged.added},snap.root),/已变化/);
    checks.push("native prefab read/merge retains engine components and importer UUIDs", "native prefab rejects a stale reviewed snapshot");
    const isolatedAsset: PsdAsset = { ...asset, atlasName: "公共资源", independentDirectory: true, layers: asset.layers.map(l => ({ ...l, config: { ...l.config, shared: false } })) };
    const isolated = new PsdExportController(settings, { uri: source }, () => psdExportDirectory(isolatedAsset));
    const isolatedBatch = makeSliceExportBatch(isolatedAsset), isolatedFile = isolatedBatch.items[0].name + ".png";
    // The host derives the atlas from its document, overriding a stale client directory.
    assert.equal(await isolated.export({ ...isolatedBatch, directory: "stale_client" }), 1);
    assert.ok(existsSync(join(second.fsPath, "ggzy", isolatedFile)));
    assert.equal(existsSync(join(second.fsPath, "stale_client")), false);
    assert.ok(existsSync(join(second.fsPath, RESOURCE_MANIFEST)));
    assert.equal(existsSync(join(second.fsPath, "ggzy", RESOURCE_MANIFEST)), false);
    const isolatedPreview = (await readWorkbenchSlices(settings, ["ggzy/" + isolatedFile]))[0];
    assert.equal(isolatedPreview.error, undefined); assert.equal(isolatedPreview.description?.source.documentId, asset.documentId);
    isolatedAsset.layers[0].config.shared = true;
    const sharedBatch = makeSliceExportBatch(isolatedAsset), sharedFile = sharedBatch.items[0].name + ".png";
    assert.equal(sharedFile, "tb.png");
    assert.equal(await isolated.export(sharedBatch), 1);
    assert.ok(existsSync(join(second.fsPath, "shared", sharedFile)));
    assert.ok(existsSync(join(second.fsPath, "ggzy", isolatedFile)));
    sharedBatch.source = { ...sharedBatch.source, documentId: "shared-replacement", psdName: "Replacement.psd" };
    assert.equal(await isolated.export(sharedBatch), 1);
    const ledger = JSON.parse(readFileSync(join(second.fsPath, RESOURCE_MANIFEST), "utf8"));
    assert.equal(ledger.version, 2);
    assert.equal(ledger.resources.find((r: { file: string }) => r.file === "shared/" + sharedFile).source.documentId, "shared-replacement");
    assert.equal((await readWorkbenchSlices(settings, ["shared/" + sharedFile]))[0].error, undefined);
    isolatedAsset.layers[0].config.shared = false; isolatedAsset.layers[0].config.exportName = "custom_icon";
    isolatedAsset.atlasName = "Other";
    assert.equal(await isolated.export(makeSliceExportBatch(isolatedAsset)), 1);
    assert.ok(existsSync(join(second.fsPath, "other/other_custom_icon.png")));
    delete isolatedAsset.independentDirectory;
    assert.equal(await isolated.export(makeSliceExportBatch(isolatedAsset)), 1);
    assert.ok(existsSync(join(second.fsPath, "unclassified/other_custom_icon.png")));
    await settings.set("resources", first);
    assert.equal(await isolated.export(makeSliceExportBatch(isolatedAsset)), 1);
    assert.ok(existsSync(join(first.fsPath, "unclassified/other_custom_icon.png")));
    assert.equal(isolated.directoryLabel, first.fsPath);
    for (const atlasName of ["builtin", "SHARED", "Unclassified"]) {
      isolatedAsset.atlasName = atlasName;
      await assert.rejects(isolated.export(sharedBatch), /保留目录名/);
    }
    isolatedAsset.independentDirectory = true; isolatedAsset.atlasName = "CON";
    await assert.rejects(isolated.export(sharedBatch), /独立目录/);
    const invalid = new PsdExportController(settings, { uri: source }, () => "../outside");
    await assert.rejects(invalid.export(batch), /无效/);
    assert.equal(existsSync(join(directory, "outside")), false);
    checks.push("PSD independent atlas directory is rooted directly and uses the root ledger", "host atlas policy overrides stale client directories", "shared output takes precedence over independent atlas and transfers provenance", "PSD atlas and directory switches and root changes update destinations", "reserved atlas names and unsafe independent folders reject before writes");
    const values = new Map<string, unknown>([[LEGACY_RESOURCE_DIRECTORY_KEY, first.toString()]]);
    const globalValues = new Map<string, number>();
    const context = {
      workspaceState: { keys: () => [...values.keys()], get: (key: string, fallback?: unknown) => values.has(key) ? values.get(key) : fallback, update: async (key: string, value: unknown) => { values.set(key, value); } },
      globalState: { keys: () => [...globalValues.keys()], setKeysForSync: () => {}, get: (key: string) => globalValues.get(key), update: async (key: string, value: number) => { globalValues.set(key, value); } }
    } as Pick<vscode.ExtensionContext, "workspaceState" | "globalState">;
    const revealed: string[] = [];
    const controller = new WorkbenchSettingsController(context, async () => undefined, async uri => { revealed.push(uri.toString()); });
    const received: unknown[] = [];
    let send: (message: unknown) => Promise<void>;
    const listener = controller.attach({ webview: { postMessage: async (value: unknown) => { received.push(value); return true; }, onDidReceiveMessage: (handle: typeof send) => { send = handle; return new vscode.Disposable(() => {}); } } } as unknown as vscode.WebviewPanel, source);
    await send!({ type: "panelWidth", mode: "prototype", side: "left", width: 388 });
    await send!({ type: "panelWidth", mode: "slice", side: "right", width: 410 });
    await send!({ type: "panelWidth", mode: "slice", side: "right", width: 277 });
    assert.deepEqual(controller.snapshot().panelWidths, { prototype: { left: 388, right: 280 }, slice: { left: 278, right: 410 } });
    assert.equal(controller.directory("resources")?.toString(), first.toString());
    await controller.reveal("resources");
    assert.deepEqual(revealed, [first.toString()]);
    assert.equal(await controller.choose("resources", source), false);
    assert.equal(values.has(EXPORT_SETTINGS_KEY), false);
    await controller.set("prefabs", prefab);
    assert.ok(received.some((value: any) => value.settings.prefabDirectory === prefab.fsPath));
    const reopened = new WorkbenchSettingsController(context);
    assert.deepEqual(reopened.snapshot().panelWidths, controller.snapshot().panelWidths);
    checks.push("prototype and slice widths restore independently from profile settings");
    assert.equal(reopened.directory("resources")?.toString(), first.toString());
    assert.equal(reopened.directory("prefabs")?.toString(), prefab.toString());
    await reopened.set("resources");
    assert.equal(controller.directory("resources"), undefined);
    await assert.rejects(reopened.reveal("resources"), /选择资源导出根目录/);
    await assert.rejects(reopened.set("resources", vscode.Uri.file(join(first.fsPath, filename))), /文件夹/);
    assert.equal(reopened.directory("resources"), undefined);
    values.set(EXPORT_SETTINGS_KEY, { version: 1, resources: "invalid" });
    const invalidSettings = await readWorkbenchSlices(reopened, [filename]);
    assert.match(invalidSettings[0].error!, /目录/);
    listener.dispose(); controller.dispose(); reopened.dispose();
    checks.push("settings persist through controller recreation and legacy migration", "folder picker cancellation preserves configuration and broadcasts changes", "file manager reveal uses only the configured resource root", "missing resource roots reject reveal without an arbitrary path", "invalid directory rejected without restoring cleared legacy path", "preview returns invalid settings as resource diagnostics");
  } finally {
    await settings.set("resources", resources); await settings.set("prefabs", prefabs);
  }
  return checks;
}
